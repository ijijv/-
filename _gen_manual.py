def set_font(run, name=BODY_FONT, size=BODY_SIZE, bold=False, color=None):
    run.font.size = size
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    for k in ('w:eastAsia', 'w:ascii', 'w:hAnsi'):
        rFonts.set(qn(k), name)


def h1(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(6)
    set_font(p.add_run(text), size=Pt(15), bold=True)


def h2(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after = Pt(3)
    set_font(p.add_run(text), size=Pt(12), bold=True)


def para(text, indent=True):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.space_after = Pt(3)
    if indent:
        pf.first_line_indent = Pt(21)
    set_font(p.add_run(text))
    return p


def bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(2)
    set_font(p.add_run(text))
    return p


def table(rows, headers, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]
        set_font(p.add_run(htxt), size=Pt(9.5), bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            set_font(p.add_run(val), size=Pt(9))
    for r in t.rows:
        for i, w in enumerate(widths):
            r.cells[i].width = Cm(w)
    return t


def img(name, caption):
    path = os.path.join(SHOTS, name)
    if os.path.exists(path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(2)
        p.add_run().add_picture(path, width=IMG_WIDTH)
    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cp.paragraph_format.space_after = Pt(6)
    set_font(cp.add_run(caption), size=Pt(9), color=(0x55, 0x55, 0x55))


def add_page_field(paragraph, prefix='第 ', suffix=' 页'):
    r0 = paragraph.add_run(prefix)
    set_font(r0, size=Pt(9))
    run = paragraph.add_run()
    b = OxmlElement('w:fldChar')
    b.set(qn('w:fldCharType'), 'begin')
    i = OxmlElement('w:instrText')
    i.set(qn('xml:space'), 'preserve')
    i.text = ' PAGE '
    e = OxmlElement('w:fldChar')
    e.set(qn('w:fldCharType'), 'end')
    run._r.append(b)
    run._r.append(i)
    run._r.append(e)
    set_font(run, size=Pt(9))
    r1 = paragraph.add_run(suffix)
    set_font(r1, size=Pt(9))


def page_break():
    p = doc.add_paragraph()
    r = p.add_run()
    br = OxmlElement('w:br')
    br.set(qn('w:type'), 'page')
    r._r.append(br)


